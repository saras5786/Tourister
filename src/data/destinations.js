export const getRouteInfo = (source, destination) => {
  if (!source || !destination) return null;
  if (source === destination) {
    return {
      distance: 0,
      isLocal: true,
      flight: "N/A",
      train: "Local Metro / Suburban Rail",
      bus: "City EV Bus Transit",
      car: "Prepaid Auto / Cab (15-45 mins)",
      eco: "Zero Intercity CO2",
    };
  }

  const key1 = `${source}-${destination}`;
  const key2 = `${destination}-${source}`;

  if (distanceMatrix[key1]) return { ...distanceMatrix[key1], isLocal: false };
  if (distanceMatrix[key2]) return { ...distanceMatrix[key2], isLocal: false };

  const estDist = Math.floor(Math.random() * 250 + 450);
  return {
    distance: estDist,
    isLocal: false,
    flight: "1h 30m - 2h 30m",
    train: `${Math.round(estDist / 55)}h`,
    bus: `${Math.round(estDist / 45)}h`,
    car: `${Math.round(estDist / 50)}h`,
    eco: `${(estDist * 0.00007).toFixed(2)}t CO2`,
  };
};

